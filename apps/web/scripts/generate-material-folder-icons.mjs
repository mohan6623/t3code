// usage: node apps/web/scripts/generate-material-folder-icons.mjs <unpacked material-icon-theme dir>
//   npm pack material-icon-theme && tar xzf material-icon-theme-*.tgz   (gives ./package)
import * as NodeFs from "node:fs";
import * as NodePath from "node:path";
import * as NodeUrl from "node:url";

const packageDir = process.argv[2];
if (!packageDir) {
  console.error("usage: generate-material-folder-icons.mjs <unpacked material-icon-theme dir>");
  process.exit(1);
}
const scriptDir = NodePath.dirname(NodeUrl.fileURLToPath(import.meta.url));
const outPath = NodePath.join(
  scriptDir,
  "../src/components/files/materialFolderIcons.generated.ts",
);
const manifest = JSON.parse(
  NodeFs.readFileSync(NodePath.join(packageDir, "dist/material-icons.json"), "utf8"),
);
const { version } = JSON.parse(
  NodeFs.readFileSync(NodePath.join(packageDir, "package.json"), "utf8"),
);

/** "folder-src" -> "src"; the plain folder icon is "". Open icons add "-open". */
const shortId = (iconId) => (iconId === "folder" ? "" : iconId.replace(/^folder-/, ""));

/** The theme lists ".rust", "_rust", "__rust__" and so on; all share one icon. Keep the base name. */
const baseFolderName = (name) =>
  name
    .toLowerCase()
    .replace(/^[._-]+/, "")
    .replace(/_+$/, "");
const names = {};
for (const [name, iconId] of Object.entries(manifest.folderNames)) {
  const key = baseFolderName(name);
  if (names[key] !== undefined && names[key] !== shortId(iconId)) {
    throw new Error(`folder name variants of "${key}" use different icons`);
  }
  names[key] = shortId(iconId);
}
const iconIds = new Set(Object.values(manifest.folderNames));
iconIds.add(manifest.folder);
const svgs = {};
for (const iconId of [...iconIds].toSorted()) {
  for (const id of [iconId, `${iconId}-open`]) {
    const definition = manifest.iconDefinitions[id];
    if (!definition) continue;
    const svg = NodeFs.readFileSync(NodePath.join(packageDir, "dist", definition.iconPath), "utf8")
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/\s+/g, " ")
      .replace(/> </g, "><")
      .replaceAll('"', "'")
      .trim();
    svgs[shortId(id.replace(/-open$/, "")) + (id.endsWith("-open") ? "-open" : "")] = svg;
  }
}

const source = `// Generated by apps/web/scripts/generate-material-folder-icons.mjs. Do not edit.
// Folder icons from material-icon-theme ${version}.
// MIT License, Copyright (c) 2025 Material Extensions.
// https://github.com/material-extensions/vscode-material-icon-theme

/**
 * Folder base name (lower case, without leading ".", "_" or "-" and trailing
 * "_") -> icon id. "" is the plain folder.
 */
export const MATERIAL_FOLDER_ICON_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(names, null, 2)};

/** Icon id -> SVG markup. An open folder's id ends in "-open". */
export const MATERIAL_FOLDER_ICON_SVGS: Readonly<Record<string, string>> = ${JSON.stringify(svgs, null, 2)};
`;
NodeFs.writeFileSync(outPath, source);
console.log(
  `wrote ${outPath}: ${Object.keys(names).length} names, ${Object.keys(svgs).length} icons, ${source.length} bytes`,
);
