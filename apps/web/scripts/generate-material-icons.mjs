// material-icon-theme package (MIT, Copyright (c) 2025 Material Extensions).
//
// usage: node apps/web/scripts/generate-material-icons.mjs <unpacked material-icon-theme dir>
//   npm pack material-icon-theme && tar xzf material-icon-theme-*.tgz   (gives ./package)
import * as NodeFs from "node:fs";
import * as NodePath from "node:path";
import * as NodeUrl from "node:url";

const packageDir = process.argv[2];
if (!packageDir) {
  console.error("usage: generate-material-icons.mjs <unpacked material-icon-theme dir>");
  process.exit(1);
}
const scriptDir = NodePath.dirname(NodeUrl.fileURLToPath(import.meta.url));
const outPath = NodePath.join(scriptDir, "../src/components/files/materialIcons.generated.ts");
const manifest = JSON.parse(
  NodeFs.readFileSync(NodePath.join(packageDir, "dist/material-icons.json"), "utf8"),
);
const { version } = JSON.parse(
  NodeFs.readFileSync(NodePath.join(packageDir, "package.json"), "utf8"),
);

/** The theme lists ".rust", "_rust", "__rust__" and so on; all share one icon. Keep the base name. */
const baseFolderName = (name) =>
  name
    .toLowerCase()
    .replace(/^[._-]+/, "")
    .replace(/_+$/, "");
const folderNames = {};
for (const [name, iconId] of Object.entries(manifest.folderNames)) {
  const key = baseFolderName(name);
  if (folderNames[key] !== undefined && folderNames[key] !== iconId) {
    throw new Error(`folder name variants of "${key}" use different icons`);
  }
  folderNames[key] = iconId;
}

/** File names and extensions match without case, as in VS Code. The first entry wins. */
const lowerKeys = (map) => {
  const result = {};
  for (const [key, iconId] of Object.entries(map)) result[key.toLowerCase()] ??= iconId;
  return result;
};
const fileNames = lowerKeys(manifest.fileNames);
const fileExtensions = lowerKeys(manifest.fileExtensions);

const iconIds = new Set([
  manifest.file,
  manifest.folder,
  ...Object.values(folderNames),
  ...Object.values(fileNames),
  ...Object.values(fileExtensions),
]);
const svgs = {};
for (const iconId of [...iconIds].toSorted()) {
  const ids = iconId.startsWith("folder") ? [iconId, `${iconId}-open`] : [iconId];
  for (const id of ids) {
    const definition = manifest.iconDefinitions[id];
    if (!definition) continue;
    svgs[id] = NodeFs.readFileSync(NodePath.join(packageDir, "dist", definition.iconPath), "utf8")
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/\s+/g, " ")
      .replace(/> </g, "><")
      .replaceAll('"', "'")
      .trim();
  }
}
for (const [what, map] of Object.entries({ folderNames, fileNames, fileExtensions })) {
  for (const [key, id] of Object.entries(map)) {
    if (!svgs[id]) throw new Error(`${what}["${key}"] uses icon "${id}", which has no SVG`);
  }
}

const json = (value) => JSON.stringify(value, null, 2);
const source = `// Generated by apps/web/scripts/generate-material-icons.mjs. Do not edit.
// File and folder icons from material-icon-theme ${version}.
// MIT License, Copyright (c) 2025 Material Extensions.
// https://github.com/material-extensions/vscode-material-icon-theme

/** Icon for a file that no name or extension matches. */
export const MATERIAL_FILE_ICON = ${JSON.stringify(manifest.file)};

/** Icon for a folder that no name matches. Its open icon adds "-open". */
export const MATERIAL_FOLDER_ICON = ${JSON.stringify(manifest.folder)};

/**
 * Folder base name (lower case, without leading ".", "_" or "-" and trailing
 * "_") -> icon id. Open folders use the id plus "-open".
 */
export const MATERIAL_FOLDER_ICON_NAMES: Readonly<Record<string, string>> = ${json(folderNames)};

/** Lower-case file name -> icon id. */
export const MATERIAL_FILE_ICON_NAMES: Readonly<Record<string, string>> = ${json(fileNames)};

/** Lower-case file extension, without its first dot ("ts", "d.ts") -> icon id. */
export const MATERIAL_FILE_ICON_EXTENSIONS: Readonly<Record<string, string>> = ${json(fileExtensions)};

/** Icon id -> SVG markup. */
export const MATERIAL_ICON_SVGS: Readonly<Record<string, string>> = ${json(svgs)};
`;
NodeFs.writeFileSync(outPath, source);
console.log(
  `wrote ${outPath}: ${Object.keys(folderNames).length} folder names, ${Object.keys(fileNames).length} file names, ${Object.keys(fileExtensions).length} extensions, ${Object.keys(svgs).length} icons, ${source.length} bytes`,
);
